export function getCardsByTopic(topic: string): QuizCard[] {
  return cards.filter((card) => card.topic === topic);
}

export function getAllTopics(): string[] {
  return Object.keys(TOPIC_LABELS);
}

export function getSessionCards(topic: string): QuizCard[] {
  if (topic === "numbers") return buildNumberSession();
  if (topic === "ordinals") return buildOrdinalSession();
  return getCardsByTopic(topic);
}

export function getDistractorPool(topic: string): QuizCard[] {
  if (topic === "numbers") return numberDistractorPool();
  if (topic === "ordinals") return ordinalDistractorPool();
  return getCardsByTopic(topic);
}

export function getSessionSize(topic: string): number {
  if (topic === "numbers") return NUMBER_SESSION_SIZE;
  if (topic === "ordinals") return ORDINAL_SESSION_SIZE;
  return getCardsByTopic(topic).length;
}
